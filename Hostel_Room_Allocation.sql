CREATE OR REPLACE FUNCTION fn_free_beds(p_room_id integer)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE v_capacity integer; v_occupied integer;
BEGIN
 SELECT capacity INTO v_capacity FROM rooms WHERE room_id=p_room_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID %',p_room_id; END IF;
 SELECT count(*) INTO v_occupied FROM allocations WHERE room_id=p_room_id AND status='ACTIVE';
 RETURN v_capacity-v_occupied;
END $$;

CREATE OR REPLACE PROCEDURE pr_allocate_room(p_student_id integer,p_room_id integer,p_allocated_on date)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM students WHERE student_id=p_student_id) THEN RAISE EXCEPTION 'Unknown student'; END IF;
 IF NOT EXISTS(SELECT 1 FROM rooms WHERE room_id=p_room_id) THEN RAISE EXCEPTION 'Unknown room'; END IF;
 IF p_allocated_on IS NULL THEN RAISE EXCEPTION 'Allocation date is required'; END IF;
 IF EXISTS(SELECT 1 FROM allocations WHERE student_id=p_student_id AND status='ACTIVE') THEN RAISE EXCEPTION 'Student already has an active allocation'; END IF;
 IF fn_free_beds(p_room_id)<=0 THEN RAISE EXCEPTION 'Room is full'; END IF;
 INSERT INTO allocations(student_id,room_id,allocated_on,released_on,status)
 VALUES(p_student_id,p_room_id,p_allocated_on,NULL,'ACTIVE');
END $$;

CREATE OR REPLACE FUNCTION trg_allocation_rules_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_capacity integer; v_occupied integer;
BEGIN
 IF NEW.status='ACTIVE' THEN
  -- Serialize allocations into a room to protect capacity from concurrent inserts.
  SELECT capacity INTO v_capacity FROM rooms WHERE room_id=NEW.room_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room'; END IF;
  IF EXISTS(SELECT 1 FROM allocations a WHERE a.student_id=NEW.student_id AND a.status='ACTIVE'
    AND a.allocation_id IS DISTINCT FROM NEW.allocation_id) THEN
    RAISE EXCEPTION 'Student already has an active allocation';
  END IF;
  SELECT count(*) INTO v_occupied FROM allocations a WHERE a.room_id=NEW.room_id AND a.status='ACTIVE'
    AND a.allocation_id IS DISTINCT FROM NEW.allocation_id;
  IF v_occupied>=v_capacity THEN RAISE EXCEPTION 'Room capacity exceeded'; END IF;
  NEW.released_on:=NULL;
 ELSE
  IF NEW.released_on IS NULL THEN RAISE EXCEPTION 'ENDED allocation requires a release date'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER allocations_enforce BEFORE INSERT OR UPDATE ON allocations
FOR EACH ROW EXECUTE FUNCTION trg_allocation_rules_fn();

CREATE OR REPLACE VIEW v_room_occupancy AS
SELECT r.room_id,r.room_number,r.capacity,count(a.allocation_id) FILTER(WHERE a.status='ACTIVE')::integer AS occupied_beds,
r.capacity-count(a.allocation_id) FILTER(WHERE a.status='ACTIVE')::integer AS free_beds
FROM rooms r LEFT JOIN allocations a USING(room_id) GROUP BY r.room_id,r.room_number,r.capacity;

CREATE INDEX idx_allocations_active_room ON allocations(room_id) WHERE status='ACTIVE';
EXPLAIN SELECT * FROM allocations WHERE room_id=1 AND status='ACTIVE';

CREATE OR REPLACE PROCEDURE pr_refresh_occupancy()
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO occupancy_snapshot(snapshot_date,room_id,occupied_beds,free_beds)
 SELECT CURRENT_DATE,r.room_id,count(a.allocation_id) FILTER(WHERE a.status='ACTIVE')::integer,
 r.capacity-count(a.allocation_id) FILTER(WHERE a.status='ACTIVE')::integer
 FROM rooms r LEFT JOIN allocations a USING(room_id) GROUP BY r.room_id,r.capacity
 ON CONFLICT(snapshot_date,room_id) DO UPDATE
 SET occupied_beds=EXCLUDED.occupied_beds,free_beds=EXCLUDED.free_beds;
END $$;
