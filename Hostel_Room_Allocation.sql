

CREATE TABLE students(student_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,student_number varchar(30) UNIQUE NOT NULL,full_name text NOT NULL);
CREATE TABLE rooms(room_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,room_number varchar(20) UNIQUE NOT NULL,capacity integer NOT NULL CHECK(capacity>0));
CREATE TABLE allocations(
 allocation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id integer NOT NULL REFERENCES students(student_id),room_id integer NOT NULL REFERENCES rooms(room_id),
 allocated_on date NOT NULL,released_on date,
 status text NOT NULL CHECK(status IN('ACTIVE','ENDED')),
 CHECK((status='ACTIVE' AND released_on IS NULL) OR (status='ENDED' AND released_on IS NOT NULL))
);
CREATE TABLE occupancy_snapshot(
 snapshot_date date NOT NULL,room_id integer NOT NULL REFERENCES rooms(room_id),
 occupied_beds integer NOT NULL,free_beds integer NOT NULL,
 PRIMARY KEY(snapshot_date,room_id)
);
